export const calculateCreditCost = (quantity = 1) => {
  const count = Math.max(1, Number(quantity) || 1);
  const basePricePerSong = 599;

  // Tiered discounts
  let discountPercent = 0;
  if (count >= 10) {
    discountPercent = 20;
  } else if (count >= 5) {
    discountPercent = 10;
  }

  const rawSubtotal = count * basePricePerSong;
  const discountAmount = Math.round((rawSubtotal * discountPercent) / 100);
  const effectiveSubtotal = rawSubtotal - discountAmount;
  const effectivePricePerSong = Math.round(effectiveSubtotal / count);

  const gstRate = 0.18;
  const gstAmount = Number((effectiveSubtotal * gstRate).toFixed(2));
  const totalPayable = Number((effectiveSubtotal + gstAmount).toFixed(2));

  return {
    credits: count,
    basePricePerSong,
    discountPercent,
    savings: discountAmount,
    effectivePricePerSong,
    subtotal: effectiveSubtotal,
    gstRate: '18%',
    gstAmount,
    totalPayable
  };
};

